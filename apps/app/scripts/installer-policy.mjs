import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../installer/", import.meta.url);
const policy = (
  await readFile(new URL("privacy-policy.txt", root), "utf8")
).replace(/\r\n/g, "\n");
const fingerprint = createHash("sha256").update(policy).digest("hex");
const version = `; Generated by scripts/installer-policy.mjs. Do not edit.\n!define AZURIA_PRIVACY_VERSION "${fingerprint}"\n`;
const escape = (text) =>
  [...text]
    .map((char) => {
      if ("\\{}".includes(char)) return "\\" + char;
      const units = char.split("").map((c) => c.charCodeAt(0));
      return units
        .map((n) =>
          n < 128 ? String.fromCharCode(n) : `\\u${n > 32767 ? n - 65536 : n}?`,
        )
        .join("");
    })
    .join("");
const rtf =
  "{\\rtf1\\ansi\\deff0\\uc1{\\fonttbl{\\f0 Segoe UI;}}\n\\f0\\fs20\n" +
  policy
    .split("\n")
    .map((line) =>
      /^[A-Z][A-Z ,—-]+$/.test(line)
        ? `\\b ${escape(line)}\\b0\\par\n`
        : `${escape(line)}\\par\n`,
    )
    .join("") +
  "}\n";
for (const [name, value] of [
  ["privacy-version.nsh", version],
  ["privacy-policy.rtf", rtf],
]) {
  const url = new URL(name, root);
  if (process.argv.includes("--check")) {
    if ((await readFile(url, "utf8")).replace(/\r\n/g, "\n") !== value)
      throw Error(
        `Regenerate ${name} with node scripts/installer-policy.mjs after editing the policy.`,
      );
  } else await writeFile(url, value);
}
console.log("Installer privacy policy and version fingerprint match.");
